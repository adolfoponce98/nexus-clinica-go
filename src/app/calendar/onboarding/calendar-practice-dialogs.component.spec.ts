import { TestBed } from '@angular/core/testing';
import { CalendarOnboardingComponent } from './calendar-onboarding.component';
import { CalendarPracticeDialogsComponent } from './calendar-practice-dialogs.component';
describe('Practice replicas of the calendar dialogs', () => {
  afterEach(() => vi.unstubAllGlobals());
  function setup(view: 'month' | 'week' | 'day' = 'month') {
    const p = new CalendarOnboardingComponent();
    p.initialView = view;
    p.begin();
    p.selectSlot(17, view === 'month' ? '' : '11:00');
    const fixture = TestBed.createComponent(CalendarPracticeDialogsComponent);
    fixture.componentRef.setInput('p', p);
    fixture.detectChanges();
    return { p, fixture, c: fixture.componentInstance, el: fixture.nativeElement as HTMLElement };
  }
  it('opens inline suggestions on focus, filters while typing, and prefills the selected patient', () => {
    const { p, fixture, el } = setup();
    const input = el.querySelector<HTMLInputElement>('[data-practice-patient]')!;
    input.focus();
    fixture.detectChanges();
    expect(el.querySelector('[role=listbox]')).toBeTruthy();
    expect(el.querySelectorAll('[role=option]')).toHaveLength(3);
    input.value = 'Carlos';
    input.dispatchEvent(new Event('input', { bubbles: true }));
    fixture.detectChanges();
    expect(el.querySelectorAll('[role=option]')).toHaveLength(1);
    el.querySelector<HTMLButtonElement>('[role=option]')!.click();
    fixture.detectChanges();
    expect(p.form.name).toBe('Carlos Paciente Demo');
    expect(p.form.phone).toBe('000 000 0002');
    expect(el.querySelector('[role=listbox]')).toBeNull();
    expect(el.querySelector('.picker-card')).toBeNull();
    const reason = el.querySelector<HTMLInputElement>('[data-practice-reason]')!;
    reason.focus();
    fixture.detectChanges();
    expect(el.querySelectorAll('[role=option]')).toHaveLength(3);
    reason.value = 'seguimiento';
    reason.dispatchEvent(new Event('input', { bubbles: true }));
    fixture.detectChanges();
    el.querySelector<HTMLButtonElement>('[role=option]')!.click();
    fixture.detectChanges();
    expect(p.form.reason).toBe('Consulta de seguimiento');
    expect(p.serviceId).toBe('demo-followup');
  });
  it('keeps the original month time chips and the fixed start time in week and day forms', () => {
    const { fixture, c, el } = setup();
    expect(el.querySelector('app-practice-booking-date-picker')).toBeTruthy();
    expect(el.textContent).toContain('Horarios Libres Disponibles');
    expect(c.filteredAvailableTimeSlots.some((s) => s.time === '10:00')).toBe(false);
    c.p.view = 'week';
    fixture.changeDetectorRef.markForCheck();
    fixture.detectChanges();
    expect(el.querySelector('app-practice-booking-date-picker')).toBeNull();
    expect(el.textContent).toContain('Hora de Inicio');
    expect(el.textContent).not.toContain('Horarios Libres Disponibles');
  });
  it('renders the original detail and cost controls without calling any service', () => {
    const fetch = vi.fn();
    vi.stubGlobal('fetch', fetch);
    const { p, fixture, c, el } = setup('day');
    p.form = { name: 'Demo', reason: 'Revisión', phone: '', email: '' };
    p.save();
    p.openDetail();
    fixture.changeDetectorRef.markForCheck();
    fixture.detectChanges();
    expect(el.querySelector('.detail-card')?.classList.contains('max-w-md')).toBe(true);
    expect(el.textContent).toContain('Horario Reservado');
    expect(el.textContent).toContain('Costo y pago de la consulta');
    expect(el.textContent).toContain('Cancelar Cita');
    c.begin();
    c.cost = 500;
    c.paid = 200;
    c.save();
    expect(c.appointment.amountPaid).toBe(200);
    expect(fetch).not.toHaveBeenCalled();
    c.executeCancelAppointment();
    expect(p.appointment?.status).toBe(0);
    c.promptCancelAppointment();
    c.executeCancelAppointment();
    expect(p.appointment?.status).toBe(2);
  });
  it('guides manual capture through contacts, optional email, reason, time and save', () => {
    const { p, c } = setup();
    expect(p.bookingGuide).toBe('name');
    c.onPatientInput({ target: { value: 'Paciente inventado' } } as any);
    expect(p.bookingGuide).toBe('patient-choice');
    expect(p.coach.target).toContain('patient-name');
    p.continueGuide();
    expect(p.bookingGuide).toBe('phone');
    p.continueGuide();
    expect(p.bookingGuide).toBe('email');
    expect(p.coach.nextLabel).toBe('Omitir correo');
    p.continueGuide();
    expect(p.bookingGuide).toBe('reason');
    c.onReasonInput({ target: { value: 'Revisión manual' } } as any);
    expect(p.bookingGuide).toBe('reason-choice');
    p.continueGuide();
    expect(p.bookingGuide).toBe('time');
    c.selectModalHour('11:00');
    expect(p.bookingGuide).toBe('save');
    expect(p.coach.target).toContain('save');
  });
  it('skips already filled contact steps for a selected patient and skips time selection in day view', () => {
    const { p, c } = setup('day');
    c.selectPatient({ id: 'demo-carlos' });
    expect(p.bookingGuide).toBe('reason');
    expect(p.form.phone).toBe('000 000 0002');
    c.selectServiceReason({ id: 'demo-followup' });
    expect(p.bookingGuide).toBe('save');
    expect(p.coach.description).toContain('hora ya quedó seleccionada');
    c.saveAppointment();
    expect(p.coach.target).toContain('appointment');
    c.p.openDetail();
    expect(p.coach.target).toContain('cancel');
    c.promptCancelAppointment();
    expect(p.coach.target).toContain('confirm-cancel');
  });
});
